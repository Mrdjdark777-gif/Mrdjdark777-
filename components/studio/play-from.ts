/**
 * Откуда начинать выпуск. Решает страница, а не плеер.
 *
 * До этого решение было размазано: веб знал про «продолжить», нативный плеер
 * держал собственное последнее место и подставлял его, когда веб молчал, —
 * и выпуск, открытый из каталога, продолжался с середины вопреки просьбе
 * начинать сначала. Теперь место всегда приходит сверху и явно.
 */
export type PlayFrom=
 /** Открыли из каталога или с кадра главной — играем с начала. */
 |'begin'
 /** Попросили строкой «Продолжить» — встаём на сохранённое место. */
 |'resume'
 /** Экран пересоздали (поворот, возврат в приложение), звук шёл сам — не трогаем. */
 |'keep';
