def main() -> None:
    registry = TerminologyRegistry.load(TERMINOLOGY_PATH)
    enriched = 0
    added = 0

    for canonical_name, phrases in ENRICH_EXISTING.items():
        term = registry.find(canonical_name)
        if term is None:
            print(f"ПРОПУЩЕНО (не найден): {canonical_name!r}")
            continue
        before = len(term.user_phrases)
        existing = set(term.user_phrases)
        term.user_phrases.extend(p for p in phrases if p not in existing)
        if len(term.user_phrases) > before:
            enriched += 1

    for data in NEW_TERMS:
        if registry.find(data["canonical_name"]) is not None:
            continue
        registry.add(Term(**data))
        added += 1

    registry.save(TERMINOLOGY_PATH)
    total_phrases = sum(len(t.user_phrases) for t in registry.terms)
    print(f"Обогащено существующих терминов: {enriched}")
    print(f"Добавлено новых терминов: {added}")
    print(f"Терминов с user_phrases: {sum(1 for t in registry.terms if t.user_phrases)}")
    print(f"Всего user_phrases в реестре: {total_phrases}")
    print(f"Итого терминов в реестре: {len(registry.terms)}")


if __name__ == "__main__":
    main()
