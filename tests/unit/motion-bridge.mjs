#!/usr/bin/env node
/**
 * Наклон телефона: страница и оболочка должны говорить на одном языке.
 *
 * В браузере положение телефона приносит событие `deviceorientation`. В
 * оболочке Android его нет: WebView не поднимает службу датчиков Chromium, и
 * обработчик не вызывается ни разу — ни ошибки, ни значения. Владелец это и
 * увидел: «карточки не двигаются вообще». Поэтому в приложении датчик читает
 * оболочка и отдаёт странице те же два числа через мост.
 *
 * Мост — это две стороны, и они написаны на разных языках в разных файлах.
 * Разойдись они хоть в одном имени — поток молча не пойдёт: ни ошибки, ни
 * движения, ровно та же картина, что была. Узнать об этом хочется здесь, а не
 * после сборки APK и установки на телефон.
 *
 * Поэтому проверяются имена и порядок: обе команды, имя события, остановка при
 * уходе с экрана и снятие слушателя при закрытии.
 */
import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import path from 'node:path';

const root = path.resolve(import.meta.dirname, '..','..');
const read = (f) => readFileSync(path.join(root, f), 'utf8');

const page = read('hooks/use-tilt.ts');
const shell = read('android/app/src/main/java/com/truethrills/listener/NativeBridge.java');
const client = read('lib/native-client.ts');

// Команды. Их две, и обе стороны обязаны знать обе.
for (const method of ['motion.start', 'motion.stop']) {
 assert.ok(page.includes("'" + method + "'"), 'страница не умеет посылать ' + method);
 assert.ok(shell.includes('"' + method + '"'), 'оболочка не умеет принимать ' + method);
}

// Имя события. Оболочка шлёт поток сама, без вопроса, и страница узнаёт его
// только по этому имени.
assert.match(shell, /put\("event",\s*"motion"\)/, 'оболочка шлёт поток без имени события — страница его не узнает');
assert.match(page, /message\.event\s*!==\s*'motion'/, 'страница не отбирает событие наклона из общего потока');

// Числа. Это те же два, что дало бы событие браузера: иначе арифметика наклона,
// общая для обоих путей, посчитает не то.
for (const field of ['beta', 'gamma']) {
 assert.ok(shell.includes('"' + field + '"'), 'оболочка не шлёт ' + field);
 assert.ok(page.includes(field), 'страница не читает ' + field);
}

// Поток идёт сам по себе, без вызова. Прежний мост ставил обработчик заново на
// каждый вызов и выбрасывал всё, у чего нет номера ответа; так поток датчика
// пропал бы целиком.
assert.match(client, /typeof message\?\.event\s*===\s*'string'/,
 'мост снова выбрасывает сообщения без номера — поток датчика до страницы не дойдёт');
assert.match(client, /export function onNative/, 'на поток от оболочки нельзя подписаться');

// Батарея. Датчик не должен читаться, когда человек ушёл с экрана, и обязан
// сниматься при закрытии приложения.
assert.match(page, /visibilitychange/, 'датчик продолжит читаться в фоне и съест батарею');
assert.match(shell, /void close\(\)\s*\{[^}]*stopMotion\(\)/, 'при закрытии слушатель датчика не снимается');

// Сдвиг, а не поворот. Поворот WebView рисует заново и сыплет пиксели — это
// проверено на устройстве владельца дважды. Правило записано здесь, чтобы
// следующая правка не вернула поворот молча.
const css = read('components/studio/home-soft.css');
assert.match(css, /transform:translate3d\(var\(--tx,0px\),var\(--ty,0px\),0\)/,
 'сдвиг карточки больше не делается переносом — композитор перестанет справляться без перерисовки');
// Ни поворота, ни объёмного режима — ни в одном состоянии карточки.
//
// Это не придирка к оформлению. Первая проверка искала только rotate и нашла
// забытое правило на :active, которое срабатывало на касание — а касание есть в
// начале каждой прокрутки. На карточке включался perspective() со сжатием,
// WebView переводил слой в объёмный режим и перерисовывал заново ровно в тот
// момент, когда лента трогалась с места. Поэтому запрещены оба слова, и во всех
// состояниях: :hover, :active, в медиазапросах — везде.
{const flat=css.replace(/\/\*[\s\S]*?\*\//g, '');     // комментарии не в счёт
 const bad=[];
 for (const rule of flat.matchAll(/([^{}]+)\{([^{}]*)\}/g)) {
  const [, selector, body] = rule;
  if (!/soft-art|soft-episode/.test(selector)) continue;
  const transform = body.match(/transform\s*:[^;]*/);
  if (!transform) continue;
  if (/rotate|perspective|rotate3d|matrix3d/.test(transform[0]))
   bad.push(selector.trim() + ' → ' + transform[0].trim());
 }
 assert.equal(bad.length, 0,
  'в карточку вернулся поворот или объёмный режим — WebView начнёт перерисовывать её слой и посыплет пиксели:\n   ' +
  bad.join('\n   '));}

console.log('PASS: наклон телефона доходит до страницы и в браузере, и в оболочке; обе стороны моста зовут одно и то же, датчик не читается в фоне, а карточка двигается переносом, а не поворотом');
