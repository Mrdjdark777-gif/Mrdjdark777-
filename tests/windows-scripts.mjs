#!/usr/bin/env node
/**
 * Скрипты для Windows обязаны начинаться с метки UTF-8 (BOM).
 *
 * Почему это не придирка к оформлению. Windows PowerShell 5.1 — тот, что стоит
 * в системе у владельца, — читает файл .ps1 без метки не как UTF-8, а в
 * однобайтовой кодировке системы. На русской Windows это cp1251. Каждая буква
 * кириллицы занимает в UTF-8 два байта, и при таком чтении они превращаются в
 * пару чужих знаков.
 *
 * Дальше начинается настоящая беда. Тире «—» в UTF-8 — это байты E2 80 94, а
 * байт 94 в cp1251 — правая типографская кавычка. PowerShell считает такую
 * кавычку настоящей границей строки: одно тире в комментарии открывает строку,
 * которая нигде не закрывается, и весь файл перестаёт разбираться. Владелец
 * получил ровно это: «В строке отсутствует завершающий символ», «Отсутствует
 * закрывающий знак "}"» — и обновление не запустилось вовсе.
 *
 * Метка в начале файла снимает вопрос: по ней PowerShell читает файл как UTF-8
 * и кириллица доезжает целой.
 *
 * Проверяются только .ps1. В .cmd метку ставить нельзя: cmd.exe печатает её
 * как мусор перед первой командой, и там кириллица живёт только в строках rem,
 * где искажение ничего не ломает.
 */
import assert from 'node:assert/strict';
import {readFileSync, readdirSync} from 'node:fs';
import path from 'node:path';

const root = path.resolve(import.meta.dirname, '..');
const folder = path.join(root, 'scripts');
const BOM = Buffer.from([0xef, 0xbb, 0xbf]);

// Байты, которые в cp1251 становятся типографскими кавычками. Именно они
// ломают разбор: PowerShell принимает их за границу строки.
const QUOTES = new Map([[0x91, '‘'], [0x92, '’'], [0x93, '“'], [0x94, '”']]);

const files = readdirSync(folder).filter((f) => f.endsWith('.ps1')).sort();
assert.ok(files.length, 'в scripts/ не осталось ни одного .ps1 — проверять нечего');

let checked = 0;
for (const name of files) {
 const bytes = readFileSync(path.join(folder, name));
 const ascii = bytes.every((b) => b < 0x80);
 if (ascii) continue;                      // латиница читается одинаково в любой кодировке
 checked += 1;

 assert.ok(bytes.subarray(0, 3).equals(BOM),
  'scripts/' + name + ' без метки UTF-8: Windows PowerShell прочитает его в cp1251 и кириллица развалится');

 // И называем опасность поимённо: без метки вот эти байты станут кавычками.
 const found = [...new Set([...bytes.subarray(3)].filter((b) => QUOTES.has(b)))];
 if (found.length) {
  assert.ok(bytes.subarray(0, 3).equals(BOM),
   'scripts/' + name + ' содержит байты ' + found.map((b) => '0x' + b.toString(16)).join(', ') +
   ' — без метки они станут кавычками ' + found.map((b) => QUOTES.get(b)).join(' ') + ' и файл не разберётся');
 }
}

assert.ok(checked, 'ни в одном .ps1 нет кириллицы — проверка ничего не сторожит');

/**
 * Вызов родной программы обязан быть прикрыт от её же потока ошибок.
 *
 * ssh, scp и git пишут туда обычный ход работы: «From https://github.com/…»,
 * строку передачи файла. Когда поток ошибок перенаправлен — а обновление так и
 * делает, чтобы вести журнал, — PowerShell 5.1 превращает такую строку в
 * ошибку NativeCommandError, и при $ErrorActionPreference='Stop' обрывает
 * работу на первой же. Обновление у владельца падало ровно здесь, хотя сервер
 * отвечал нормально.
 *
 * Прикрытие — одна и та же пара строк вокруг вызова: снять 'Stop' и вернуть
 * его обратно в finally. Судим о родной программе по $LASTEXITCODE. Здесь
 * проверяется, что ни один вызов не остался голым.
 */
const NATIVE = /(^|[^\w])&\s+(ssh|scp)\b/;
let guarded = 0;
for (const name of files) {
 const lines = readFileSync(path.join(folder, name), 'utf8').split(/\r?\n/);
 lines.forEach((line, at) => {
  if (!NATIVE.test(line)) return;
  if (line.trimStart().startsWith('#')) return;        // в комментарии вызова нет
  guarded += 1;
  const where = 'scripts/' + name + ':' + (at + 1);
  assert.match(line, /try\s*\{.*\}\s*finally\s*\{\s*\$ErrorActionPreference\s*=\s*\$Was\s*\}/,
   where + ' — вызов родной программы не в try/finally: её поток ошибок оборвёт обновление');
  const before = lines[at - 1] ?? '';
  assert.match(before, /\$ErrorActionPreference\s*=\s*'Continue'/,
   where + " — перед вызовом родной программы не снят 'Stop': строка из её потока ошибок станет остановкой");
 });
}
// Вызовов ровно три: ssh в Invoke-Remote, ssh с паролем для копии и scp,
// которым копия скачивается. Четвёртым был scp, увозивший скрипты
// обслуживания с компьютера владельца, — его больше нет: сервер берёт их из
// своего же кода, и папка на компьютере на обновление не влияет.
assert.ok(guarded >= 3, 'вызовов ssh и scp нашлось всего ' + guarded + ' — проверка смотрит не туда');

// Ответ сервера приходит по-русски и в UTF-8. Консоль Windows читает вывод
// чужих программ в кодировке системы, и без переключения русские строки
// обновления доходят до владельца набором знаков — предупреждения он не
// прочитает, а они для него и написаны.
assert.match(readFileSync(path.join(folder, 'TrueThrills-Obnovit.ps1'), 'utf8'),
 /\[Console\]::OutputEncoding\s*=\s*\[Text\.Encoding\]::UTF8/,
 'обновление не переключает вывод консоли на UTF-8: ответы сервера дойдут кашей');

/**
 * Из вывода обновления прячутся только чужие объявления, и ничего больше.
 *
 * Владелец видел красную стену при каждом обновлении и каждый раз спрашивал,
 * что сломалось. Почти всё там — «npm warn deprecated» про пакеты внутри наших
 * зависимостей, сделать с ними нечего. Их мы убрали из вывода.
 *
 * Но прятать вывод опасно: один широкий фильтр — и неудачная установка пройдёт
 * незаметно. Поэтому здесь записано, что фильтр узкий, и что код возврата
 * установки не теряется.
 */
{
 const update = readFileSync(path.join(root, 'scripts/update-safe.sh'), 'utf8');
 const line = update.split('\n').find((l) => l.trim().startsWith('npm ci'));
 assert.ok(line, 'в обновлении больше нет установки зависимостей');
 const filters = line.match(/grep -v '([^']*)'/g) || [];
 assert.equal(filters.length, 1, 'у установки зависимостей не один фильтр вывода, а ' + filters.length);
 assert.match(line, /grep -v '\^npm warn deprecated '/,
  'фильтр вывода установки шире, чем чужие объявления, — так можно спрятать настоящую ошибку: ' + line.trim());
 assert.ok(!/\|\s*grep/.test(line) && !/\|\|\s*true/.test(line),
  'установка идёт через канал или гасит код возврата — неудачная установка станет незаметной: ' + line.trim());
 assert.ok(!/--silent|--quiet|--loglevel/.test(line),
  'установке зажали весь вывод целиком, а не только чужие объявления: ' + line.trim());

 // Проверка здоровья: сообщения неудачных попыток придерживаются, но если не
 // ответила ни одна — показываются целиком, иначе обновление молча соврёт.
 assert.ok(!/curl[^\n]*--show-error/.test(update),
  'curl снова печатает сообщение каждой неудачной попытки — владелец читает его как поломку');
 assert.match(update, /Служба не ответила на проверку здоровья/,
  'при настоящем молчании службы обновление обязано сказать об этом словами');
}

/**
 * Скрипты обслуживания не едут на сервер с компьютера владельца.
 *
 * Так было: scp увозил update-safe.sh и два помощника из папки рядом с
 * TrueThrills-Server.ps1. У владельца эта папка — распакованный архив, а не
 * рабочая копия: обновлять её нечем, и она отстала. Сервер получал старый
 * скрипт обслуживания при каждом обновлении, и правки в нём до сервера не
 * доезжали вовсе. Владелец дважды показывал на красные строки, которые я
 * дважды «починил» в файле, который туда не попадал.
 *
 * Источник теперь один — код на самом сервере. Здесь записано, что он один и
 * остался, иначе следующая правка вернёт ту же тихую беду.
 */
{
 const server = readFileSync(path.join(folder, 'TrueThrills-Server.ps1'), 'utf8');
 const from = server.indexOf("if($Action -eq 'Update')");
 assert.ok(from > 0, 'в TrueThrills-Server.ps1 больше нет ветки обновления');
 const rest = server.slice(from);
 const block = rest.slice(0, rest.indexOf('\n exit'));
 assert.ok(block.length > 200, 'ветка обновления прочиталась пустой — проверка смотрит не туда');
 // Пояснения в счёт не идут: там это слово стоит как раз в рассказе о том,
 // почему так больше не делается.
 const code = block.split('\n').filter((l) => !/^\s*#/.test(l)).join('\n');

 assert.ok(!/\bscp\b/.test(code),
  'обновление снова увозит файлы обслуживания с компьютера владельца: его папка отстаёт, и правки в этих скриптах до сервера не доходят');
 assert.ok(!/\$PSScriptRoot/.test(code),
  'обновление снова берёт файлы обслуживания из папки рядом со скриптом, а не из кода на сервере');
 for (const name of ['update-safe.sh', 'backup-data.mjs', 'verify-backup.mjs'])
  assert.ok(code.includes('/opt/truethrills/scripts/' + name),
   'обновление не берёт ' + name + ' из кода на сервере');

 // Но запускается всё равно не прямо из scripts: обновление само переписывает
 // этот каталог через git merge, а bash дочитывает исполняемый файл с диска по
 // ходу работы. Файл не должен меняться у себя под ногами.
 assert.match(code, /bash \.update-staging\/update-safe\.sh/,
  'обновление запускает скрипт прямо из каталога, который само же переписывает по ходу работы');
}

console.log('PASS: все ' + checked + ' скрипта PowerShell с кириллицей начинаются с метки UTF-8, а все ' + guarded +
 ' вызова ssh и scp прикрыты от собственного потока ошибок; из вывода обновления прячутся только чужие объявления, молчание службы по-прежнему называется словами, а скрипты обслуживания берутся из кода на сервере, а не с компьютера владельца');
