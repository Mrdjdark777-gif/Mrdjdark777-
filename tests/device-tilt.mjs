#!/usr/bin/env node
/**
 * Наклон телефона в поворот карточки — без телефона и без браузера.
 *
 * Проверять это на устройстве нечем, а ошибиться здесь легко: перепутанный
 * знак разворачивает карточку в другую сторону, и на глаз это выглядит просто
 * «как-то не так». Поэтому арифметика вынесена отдельно и проверяется числами.
 */
import {build} from 'esbuild';
import assert from 'node:assert/strict';
import path from 'node:path';

const root=process.cwd();
const {outputFiles}=await build({entryPoints:[path.join(root,'lib/device-tilt.ts')],
 bundle:true,write:false,format:'esm',platform:'node'});
const {aim,follow,ease,shadowOf,turnOf,nearOf,scaleOf,litOf,stepOf,shiftOf,STEPS,LIMIT,SPAN,REACH}=await import(
 'data:text/javascript;base64,'+Buffer.from(outputFiles[0].text).toString('base64'));

// 1. Телефон в покое — карточка стоит прямо.
{
 const t=aim(38,0);
 assert.ok(Math.abs(t.x)<0.01,'в привычном положении карточка не должна быть завёрнута: '+t.x);
 assert.ok(Math.abs(t.y)<0.01,'в покое поворота вбок быть не должно: '+t.y);
}

// 2. Наклон вбок крутит вокруг вертикальной оси, и знак именно такой.
{
 const right=aim(38,SPAN);
 assert.ok(right.y>0,'наклон телефона вправо обязан повернуть карточку вправо: '+right.y);
 assert.equal(Math.round(right.y),LIMIT,'на краю диапазона поворот равен пределу');
 const left=aim(38,-SPAN);
 assert.equal(Math.round(left.y),-LIMIT,'влево — зеркально');
}

// 3. Наклон вперёд-назад крутит вокруг горизонтальной оси.
{
 // Отодвинул верх телефона от себя (beta больше покоя) — верх карточки уходит
 // назад, то есть поворот вокруг X отрицательный.
 const away=aim(38+SPAN,0);
 assert.ok(away.x<0,'отодвинул телефон — верх карточки обязан уйти назад: '+away.x);
 const near=aim(38-SPAN,0);
 assert.ok(near.x>0,'наклонил к себе — верх карточки обязан выйти вперёд: '+near.x);
}

// 4. Дальше края диапазона карточка не заваливается.
{
 const far=aim(38+SPAN*10,SPAN*10);
 assert.ok(Math.abs(far.x)<=LIMIT+0.001&&Math.abs(far.y)<=LIMIT+0.001,
  'поворот обязан упираться в предел, а не расти без конца: '+JSON.stringify(far));
}

// 5. Телефон без датчика ничего не ломает.
{
 const none=aim(null,null);
 assert.ok(Math.abs(none.x)<0.01&&Math.abs(none.y)<0.01,
  'без показаний датчика карточка стоит прямо: '+JSON.stringify(none));
}

// 6. Сглаживание идёт К цели и не перелетает её.
{
 let now={x:0,y:0};const goal={x:LIMIT,y:-LIMIT};
 for(let i=0;i<200;i++)now=ease(now,goal);
 assert.ok(Math.abs(now.x-goal.x)<0.01&&Math.abs(now.y-goal.y)<0.01,
  'сглаживание обязано дойти до цели: '+JSON.stringify(now));
 const step=ease({x:0,y:0},goal);
 assert.ok(step.x>0&&step.x<goal.x,'один шаг сглаживания не должен прыгать в цель: '+step.x);
}

// 7. Тень уезжает в сторону, противоположную повороту: свет остаётся на месте.
{
 const right=shadowOf({x:0,y:LIMIT});
 assert.ok(right.x<0,'повернули карточку вправо — тень обязана уйти влево: '+right.x);
 const flat=shadowOf({x:0,y:0});
 assert.ok(flat.y>0,'в покое тень лежит под карточкой, а не над ней: '+flat.y);
}

// 8. Разворот по месту в карусели: середина стоит лицом, края повёрнуты.
{
 assert.ok(Math.abs(turnOf(200,200,200))<0.001,'карточка посреди полосы обязана стоять лицом');
 const right=turnOf(400,200,200),left=turnOf(0,200,200);
 assert.ok(right<0,'карточка справа от середины разворачивается правым краем назад: '+right);
 assert.ok(left>0,'слева — зеркально: '+left);
 assert.equal(Math.round(right),-Math.round(left),'развороты по краям обязаны быть зеркальными');
 assert.ok(Math.abs(turnOf(5000,200,200))<=12.001,'дальше края разворот не растёт');
 assert.ok(Math.abs(turnOf(100,200,0))<0.001,'без ширины полосы разворота нет, а не деление на ноль');
}

// 9. Близость к середине полосы: масштаб и яркость карточки.
{
 assert.equal(nearOf(200,200,200),1,'карточка посреди полосы — самая близкая');
 assert.equal(nearOf(400,200,200),0,'карточка у края полосы — самая дальняя');
 assert.equal(nearOf(0,200,200),0,'у другого края — так же');
 assert.equal(nearOf(5000,200,200),0,'дальше края ближе не становится и не уходит в минус');
 assert.equal(nearOf(100,200,0),1,'без ширины полосы карточка считается близкой, а не делится на ноль');
 // Масштаб и яркость растут вместе с близостью и не выходят за разумные пределы.
 assert.ok(scaleOf(1)>scaleOf(0),'ближняя карточка обязана быть крупнее дальней');
 assert.ok(scaleOf(1)<=1.001,'масштаб выше единицы растягивает готовую картинку и мылит края: '+scaleOf(1));
 assert.ok(scaleOf(0)>=0.78,'дальняя карточка не должна схлопываться: '+scaleOf(0));
 // Владелец просил, чтобы середина выделялась отчётливо. Разница в один-два
 // процента этого не даёт — её попросту не видно.
 assert.ok(scaleOf(1)-scaleOf(0)>=0.14,
  'середина выделена слабо: разница масштабов всего '+((scaleOf(1)-scaleOf(0))*100).toFixed(0)+'%');
 assert.ok(litOf(1)>litOf(0),'ближняя карточка обязана быть светлее дальней');
 assert.ok(litOf(0)>=0.4&&litOf(1)<=1.001,'яркость обязана оставаться в пределах: '+litOf(0)+'…'+litOf(1));
 assert.ok(litOf(1)-litOf(0)>=0.45,
  'середина притушена слабо: разница яркостей всего '+((litOf(1)-litOf(0))*100).toFixed(0)+'%');
}

// 9b. Сдвиг от наклона.
//
// Поворот WebView рисует заново и сыплет пиксели, сдвиг — нет: его делает
// композитор над готовым слоем. Поэтому наклон телефона переводится в сдвиг, и
// у этого перевода есть три обязательства: в покое не двигать ничего, на краю
// не уезжать дальше обещанного и смотреть в противоположные стороны при
// противоположных наклонах.
{
 // Ноль со знаком минус — тоже ноль: сравниваем по величине, а не побайтово.
 {const rest=shiftOf({x:0,y:0});
  assert.equal(Math.abs(rest.x)+Math.abs(rest.y),0,'в покое карточка обязана стоять на месте: '+JSON.stringify(rest));}
 const right=shiftOf({x:0,y:LIMIT}),left=shiftOf({x:0,y:-LIMIT});
 assert.ok(right.x>0&&left.x<0,'наклон вправо и влево обязан двигать карточку в разные стороны');
 assert.equal(right.x,REACH,'на краю наклона сдвиг обязан быть ровно обещанным: '+right.x);
 assert.equal(left.x,-REACH,'на другом краю — столько же в другую сторону: '+left.x);
 const away=shiftOf({x:LIMIT,y:0}),near=shiftOf({x:-LIMIT,y:0});
 assert.ok(away.y<0&&near.y>0,'наклон вперёд и назад обязан двигать карточку в разные стороны');
 // Движение именно небольшое: владелец просил «небольшое движение», а не качели.
 // Нижняя граница — тоже требование: при шести точках на телефоне владельца
 // движения не было видно вовсе. Верхняя — чтобы это было плавание, а не качели.
 assert.ok(REACH>=10&&REACH<=16,'сдвиг карточки '+REACH+' точек: меньше десяти глаз не ловит, больше шестнадцати — уже качка');
 for(const t of [{x:LIMIT*3,y:LIMIT*3},{x:-LIMIT*5,y:LIMIT*4}]){
  const far=shiftOf(t);
  assert.ok(Math.abs(far.x)<=REACH+1e-9&&Math.abs(far.y)<=REACH+1e-9,
   'кривое значение от датчика утащило карточку за предел: '+JSON.stringify(far));
 }
}

// 10. Ступени. Прокрутка даёт новое значение каждый кадр, и каждое из них —
// новая перерисовка слоя со скруглением и тенью; на быстрой прокрутке это
// видно рябью. Ступени обязаны огрублять значение, оставаясь в тех же
// пределах и не переставая расти.
{
 assert.ok(STEPS>=6&&STEPS<=24,'ступеней должно быть столько, чтобы движение осталось плавным: '+STEPS);
 assert.equal(stepOf(0),0,'ноль обязан остаться нулём');
 assert.equal(stepOf(1),1,'единица обязана остаться единицей');
 const seen=new Set();
 for(let i=0;i<=1000;i++)seen.add(stepOf(i/1000));
 assert.equal(seen.size,STEPS+1,'тысяча разных значений обязана лечь на '+(STEPS+1)+' ступеней, а легла на '+seen.size);
 // Огрубление не должно врать больше, чем на половину ступени.
 for(let i=0;i<=1000;i++){
  const v=i/1000;
  assert.ok(Math.abs(stepOf(v)-v)<=0.5/STEPS+1e-9,'ступень увела значение слишком далеко: '+v+' стало '+stepOf(v));
 }
 assert.ok(stepOf(1)>stepOf(0.5)&&stepOf(0.5)>stepOf(0),'ступени обязаны идти по возрастанию');
 assert.equal(stepOf(0.42,0),0.42,'без ступеней значение обязано проходить как есть');
}

// Нейтраль идёт за рукой. Держишь телефон круче привычного — через пару
// секунд это и есть «ровно», и наклон отсчитывается от него. С зашитыми 38°
// наклон вперёд упирался в предел и дальше не отвечал вовсе: держишь под 65°
// и наклоняешь до 75° — карточка стоит, как стояла.
{
 let rest=38;
 for(let i=0;i<48;i++)rest=follow(rest,65);                 // три секунды при шестнадцати значениях
 assert.ok(Math.abs(rest-65)<15,'за три секунды нейтраль не дошла до руки: '+rest.toFixed(1));
 const held=aim(65,0,rest),tipped=aim(75,0,rest);
 assert.ok(Math.abs(tipped.x-held.x)>LIMIT*0.2,
  'держишь телефон под 65° и наклоняешь до 75° — карточка обязана сдвинуться, а сдвиг '+(tipped.x-held.x).toFixed(2));
 const fixed=aim(65,0,38),fixedTipped=aim(75,0,38);
 assert.equal(fixed.x,fixedTipped.x,'контроль: с зашитыми 38° этот наклон упирается в предел — проверка смотрит туда');
 assert.equal(follow(null,50),50,'без прежней нейтрали берётся первое значение');
 assert.equal(follow(40,null),40,'пустое значение нейтраль не двигает');
}
console.log('PASS: наклон телефона переводится в поворот карточки с верными знаками, упирается в предел, сглаживается к цели и уводит тень в противоположную сторону; карточки в карусели разворачиваются от середины к краям зеркально; ближняя карточка крупнее и светлее дальней, разница видна глазом, а близость огрубляется до ступеней, чтобы слой не перерисовывался каждый кадр');
