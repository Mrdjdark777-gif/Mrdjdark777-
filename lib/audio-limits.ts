/**
 * Один предел размера аудио на весь путь: студия, загрузка, сервер, плеер.
 *
 * 300 МБ — это около 2 ч 10 мин при 320 кбит/с: выпуск или запись эфира на
 * полтора часа помещается с запасом. Раньше было 80 МБ, и после перехода на
 * 320 кбит/с запись в студии останавливалась уже через 33 минуты.
 * Предел nginx (scripts/install-operations.sh) держится чуть выше этого.
 */
export const AUDIO_MAX_BYTES = 300 * 1024 * 1024;
/** Запись в студии останавливается чуть раньше, чтобы черновик точно прошёл загрузку. */
export const RECORDING_STOP_BYTES = 290 * 1024 * 1024;
