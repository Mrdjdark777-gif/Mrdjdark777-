/**
 * Решения о том, когда отпускать эфир. Вынесены сюда отдельно от хука, чтобы
 * их можно было проверить без браузера (tests/live-resilience.mjs).
 *
 * Суть правила: неудачный опрос статуса — это про сеть страницы, а не про
 * звук. В приложении эфир играет нативным плеером, у которого своя буферизация
 * и своё переподключение; он переживает и смену сети, и свёрнутое приложение.
 * Раньше пять подряд неудачных опросов останавливали именно его — слушатель
 * клал телефон в карман, WebView замирал, опросы падали, и эфир обрывался
 * посреди фразы. Нативный плеер сам скажет, что он кончился.
 */

/** Сколько неудач подряд терпим, пока звук идёт из самой страницы. */
export const POLL_ERROR_LIMIT = 5;

export type PollFailure = {
  /** Неудач опроса подряд, включая текущую. */
  errors: number;
  /** Эфир играет нативным плеером приложения. */
  nativeAttached: boolean;
  /** Страница не на экране: WebView и вкладки в фоне душат таймеры и запросы. */
  hidden: boolean;
};

/** Отпускать ли эфир после неудачного опроса статуса. */
export function dropAfterPollError({errors, nativeAttached, hidden}: PollFailure): boolean {
  if (hidden) return false;
  if (nativeAttached) return false;
  return errors >= POLL_ERROR_LIMIT;
}

/**
 * Опрашивать ли статус прямо сейчас. В фоне не опрашиваем вовсе: ответа всё
 * равно никто не увидит, а неудачи копятся на ровном месте. Вернувшись на
 * экран, страница опрашивает сразу и с чистым счётчиком.
 */
export function shouldPoll(hidden: boolean): boolean {
  return !hidden;
}
