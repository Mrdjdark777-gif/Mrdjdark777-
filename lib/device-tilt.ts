/**
 * Наклон телефона в градусы поворота карточки.
 *
 * Телефон знает своё положение в пространстве: событие `deviceorientation`
 * приносит наклон вперёд-назад (beta) и влево-вправо (gamma). Карточки карусели
 * поворачиваются вслед за рукой — не съезжают в сторону, а именно
 * поворачиваются, как настоящая карточка, которую держат перед собой.
 *
 * Считается здесь, а не в компоненте, по двум причинам. Во-первых, это чистая
 * арифметика, и её можно проверить без браузера и без телефона. Во-вторых,
 * сглаживание и предел наклона — это решения, а не техника: без них карточка
 * дёргается на каждое дрожание руки и заваливается до неразличимости.
 */

/** Насколько сильно карточка поворачивается на краю диапазона. */
export const LIMIT = 9;
/** Какой наклон телефона считается краем диапазона, в градусах. */
export const SPAN = 26;
/** Доля нового значения в сглаживании: меньше — спокойнее, но с задержкой. */
export const EASE = 0.14;

export type Tilt = {x: number; y: number};

/** Держим значение в пределах ±limit. */
const clamp = (value: number, limit: number) =>
 value > limit ? limit : value < -limit ? -limit : value;

/**
 * Куда повернуть карточку при таком положении телефона.
 *
 * `beta` — наклон вперёд-назад, `gamma` — влево-вправо. Опорная точка не ноль,
 * а привычное положение телефона в руке: человек держит его не плашмя, а
 * наклонённым к себе. Без этой поправки карточка в покое стоит завёрнутой.
 */
export function aim(beta: number | null, gamma: number | null, rest = 38): Tilt {
 const forward = Number.isFinite(beta as number) ? (beta as number) - rest : 0;
 const side = Number.isFinite(gamma as number) ? (gamma as number) : 0;
 return {
  // Наклон влево-вправо крутит карточку вокруг вертикальной оси: телефон
  // повернули влево — левый край карточки уходит от нас.
  y: clamp(side / SPAN * LIMIT, LIMIT),
  // Наклон вперёд-назад крутит вокруг горизонтальной: отодвинул телефон от
  // себя — верх карточки уходит назад.
  x: clamp(-forward / SPAN * LIMIT, LIMIT),
 };
}

/** Шаг сглаживания: новое положение притягивается к цели, а не прыгает в неё. */
export function ease(now: Tilt, goal: Tilt, rate = EASE): Tilt {
 return {x: now.x + (goal.x - now.x) * rate, y: now.y + (goal.y - now.y) * rate};
}

/**
 * Насколько карточка отъезжает в сторону на краю наклона, в точках.
 *
 * Шесть — это намеренно мало. Движение должно читаться как «карточки живут», а
 * не как качели: на телефоне сдвиг в шесть точек заметен краем глаза и не
 * мешает читать названия.
 */
export const REACH = 6;

/**
 * Наклон телефона в сдвиг карточки.
 *
 * Поворот здесь пробовали дважды, и оба раза WebView рассыпал пиксели: он
 * перерисовывает повёрнутый слой заново и промахивается по скруглению. Сдвиг
 * устроен иначе — его выполняет композитор над готовым слоем, не трогая
 * содержимое. Это та же разница, что между прозрачностью и масштабом в
 * карусели, и именно поэтому сдвиг не рябит.
 *
 * Направление — как у окна: наклонил телефон влево, и то, что внутри,
 * сместилось вправо, будто смотришь в коробку сбоку.
 */
export function shiftOf(tilt: Tilt, reach = REACH): {x: number; y: number} {
 // Предел тут не лишний, хотя aim и так держит наклон в ±LIMIT. Числа приходят
 // от датчика через мост, и одно кривое значение не должно уметь утащить
 // карточку за край экрана.
 return {x: clamp(tilt.y / LIMIT * reach, reach), y: clamp(-tilt.x / LIMIT * reach, reach)};
}

/** Тень уезжает в сторону, противоположную повороту: свет остаётся на месте. */
export function shadowOf(tilt: Tilt): {x: number; y: number} {
 return {x: -tilt.y / LIMIT * 10, y: 14 + tilt.x / LIMIT * 6};
}

/**
 * Разворот карточки по её месту в карусели.
 *
 * Гироскоп есть не везде: в браузере на компьютере его нет вовсе, а в
 * оболочке Android датчик может быть выключен настройками. Объём при этом
 * пропадать не должен, поэтому карточки разворачиваются ещё и от прокрутки:
 * та, что в середине полосы, стоит к нам лицом, соседние повёрнуты, дальние —
 * сильнее. Это тот же приём, каким показывают обложки в витрине.
 *
 * `middle` — середина видимой полосы, `centre` — середина карточки, `span` —
 * половина ширины полосы. Всё в пикселях.
 */
export function turnOf(centre: number, middle: number, span: number): number {
 if (!(span > 0)) return 0;
 const away = clamp((centre - middle) / span, 1);
 // Знак: карточка справа от середины повёрнута к нам левым боком, то есть
 // её правый край уходит назад. Это отрицательный поворот вокруг Y.
 return -away * 12;
}

/**
 * Насколько карточка близка к середине полосы: 1 — ровно посередине, 0 — у края.
 *
 * Отсюда берутся и масштаб, и яркость. Поворотом это делать нельзя: WebView на
 * устройстве владельца рисовал повёрнутый слой с промахами по скруглению, и
 * вместо объёма получались рассыпавшиеся пиксели. Масштаб и прозрачность
 * выполняет тот же готовый слой, без перерисовки содержимого, — они не
 * сыплются нигде.
 */
export function nearOf(centre: number, middle: number, span: number): number {
 if (!(span > 0)) return 1;
 return 1 - Math.min(1, Math.abs(centre - middle) / span);
}

/**
 * Близость, огрублённая до ступеней.
 *
 * Прокрутка даёт новое значение каждый кадр, и каждое из них — новый масштаб.
 * Слой карточки при смене масштаба перерисовывается заново, вместе со
 * скруглением, тенью и бортиком, и на быстрой прокрутке это видно как рябь по
 * пикселям: владелец сказал «если крутишь быстрее, она рябит». Ступени убирают
 * причину: значение меняется десяток раз за всю прокрутку, а не шестьдесят раз
 * в секунду. Промежутки между ступенями сглаживает переход в стилях, поэтому
 * движение остаётся плавным.
 */
export const STEPS = 12;
export function stepOf(value: number, steps: number = STEPS): number {
 if (!(steps > 0)) return value;
 return Math.round(value * steps) / steps;
}

/**
 * Масштаб карточки по её близости к середине.
 *
 * Разброс нарочно крупный: владелец просил, чтобы середина выделялась
 * отчётливо. Выше единицы не поднимаемся никогда — увеличенный слой WebView
 * растягивает из готовой картинки, и края становятся мылом. Крупнее середина
 * делается тем, что дальние карточки мельче, а не тем, что ближняя больше.
 */
export const scaleOf = (near: number) => 0.84 + 0.16 * near;

/** Яркость карточки по её близости к середине. */
export const litOf = (near: number) => 0.5 + 0.5 * near;
